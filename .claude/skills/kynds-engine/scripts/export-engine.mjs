#!/usr/bin/env node
// Export the Kynds Engine as a self-contained package for a new Kynds game.
//
//   node .claude/skills/kynds-engine/scripts/export-engine.mjs [outDir]
//
// Run from the root of a Kynds: Medieval checkout. Writes:
//   <outDir>/package.json     kynds-engine: "." the headless half, "./render" the three.js half
//   <outDir>/src/**           src/engine, as it is (it imports nothing but itself and three)
//   <outDir>/API.md           every export of each module with its first line of documentation
//   <outDir>/GUIDE.md         docs/ENGINE.md, the engine guide
//   <outDir>/starter/         a small headless Kynds game on the engine, with its tests
// Then checks every relative import lands on a file in the package.
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.resolve(process.argv[2] ?? path.join(here, '..', 'package'));
const engine = path.resolve('src/engine');
if (!fs.existsSync(path.join(engine, 'index.ts'))) {
  console.error('Run this from the root of a Kynds: Medieval checkout (src/engine/index.ts not found).');
  process.exit(1);
}

fs.rmSync(out, { recursive: true, force: true });
const write = (rel, text) => {
  fs.mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
  fs.writeFileSync(path.join(out, rel), text);
};
const files = [];
const walk = (d, rel = '') => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (e.isDirectory()) walk(path.join(d, e.name), path.join(rel, e.name));
    else if (e.name.endsWith('.ts')) files.push(path.join(rel, e.name));
  }
};
walk(engine);
files.sort();
for (const f of files) write(path.join('src', f), fs.readFileSync(path.join(engine, f), 'utf8'));
for (const f of fs.readdirSync(path.join(here, '..', 'starter'))) write(path.join('starter', f), fs.readFileSync(path.join(here, '..', 'starter', f), 'utf8'));
if (fs.existsSync('docs/ENGINE.md')) write('GUIDE.md', fs.readFileSync('docs/ENGINE.md', 'utf8'));

const three = JSON.parse(fs.readFileSync('package.json', 'utf8')).dependencies?.three ?? '^0.170.0';
write('package.json', JSON.stringify({
  name: 'kynds-engine',
  version: '0.8.0',
  description: 'The Kynds Engine: a headless life-sim core (navigation, slots, saves, tiers, animation, build tools) and its three.js half (material features with WebGPU node versions, instancing, merging).',
  type: 'module',
  exports: { '.': './src/index.ts', './render': './src/render/index.ts' },
  files: ['src', 'API.md', 'GUIDE.md', 'starter'],
  peerDependencies: { three },
  peerDependenciesMeta: { three: { optional: true } },
  scripts: { test: 'node --test starter/*.test.ts' },
  engines: { node: '>=22.6' },
}, null, 2) + '\n');

// API reference: each module's exports, with the first sentence of the doc comment above each.
const api = ['# Kynds Engine API', '', 'Generated by `export-engine.mjs` from the source. `import { … } from \'kynds-engine\'` (headless) or `\'kynds-engine/render\'` (three.js).', ''];
for (const f of files) {
  if (f.endsWith('index.ts')) continue;
  const text = fs.readFileSync(path.join(engine, f), 'utf8');
  const head = /^(?:import[^\n]*\n)*\s*\/\*\*([\s\S]*?)\*\//.exec(text);
  const rows = [];
  // (A doc comment counts only when it sits right above the export.)
  for (const m of text.matchAll(/(?:\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?export (?:declare )?(?:abstract )?(class|function|const|interface|type) (\w+)/g)) {
    const doc = (m[1] ?? '').replace(/^\s*\* ?/gm, '').replace(/\s+/g, ' ').trim();
    const sentence = doc.split(/(?<=\.)\s/)[0] ?? '';
    const first = sentence.length > 180 ? sentence.slice(0, 177).replace(/\s+\S*$/, '') + '…' : sentence;
    rows.push(`| \`${m[3]}\` | ${m[2]} | ${first.replace(/\|/g, '\\|')} |`);
  }
  if (!rows.length) continue;
  api.push(`## \`${f.replace(/\\/g, '/')}\``, '');
  if (head) api.push(head[1].replace(/^\s*\* ?/gm, '').replace(/\s+/g, ' ').trim(), '');
  api.push('| Export | Kind | What it is |', '| --- | --- | --- |', ...rows, '');
}
write('API.md', api.join('\n'));

// Every relative import must land on a file in the package; nothing but three from outside.
const problems = [];
const check = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) check(p);
    else if (p.endsWith('.ts')) for (const m of fs.readFileSync(p, 'utf8').matchAll(/(?:from|import)\s*\(?\s*'([^']+)'/g)) {
      const spec = m[1];
      if (spec === 'three' || spec.startsWith('three/') || spec.startsWith('node:')) continue;
      if (!spec.startsWith('.')) problems.push(`${path.relative(out, p)} imports '${spec}'`);
      else if (!fs.existsSync(path.resolve(path.dirname(p), spec))) problems.push(`${path.relative(out, p)} → ${spec} (missing)`);
    }
  }
};
check(out);
if (problems.length) {
  console.error('The package is not self-contained:\n  ' + problems.join('\n  '));
  process.exit(1);
}
console.log(`kynds-engine written to ${out} (${files.length} modules, API.md, GUIDE.md, starter).`);
